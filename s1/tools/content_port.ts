const plain = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;

export function buildContentBundle(events: unknown[] = readContentEvents(EVENTS_DIR), secrets: unknown[] = readContentEvents(SECRETS_DIR), deals: unknown[] = readContentEvents(DEALS_DIR)) {
  return {
    _note: 'Generated by s1/tools/content_port.ts from S1 data. All travel events, including ev_str_*. Do not edit.',
    format: 'train-content-v1',
    events: plain((events as ContentEvent[]).filter(ev => ev.phase === 'travel')),
    secrets: plain(secrets as ContentSecret[]), deals: plain(deals as ContentDeal[]), draw: plain(S1.DRAW),
  };
}

type Action = { kind: 'advance' | 'resolve_stop' | 'choose_card' | 'cast_vote'; uid?: number; index?: number; go?: boolean };
type Part = { name: string; action: Record<string, unknown>; before: Game; after: Game; result?: unknown };
type ViewRow = { name: string; state: Game; card: Card; view: S1.CardView; costs: string[][]; pols: ReturnType<typeof S1.politicsLines>[]; choices: { index: number; after: Game }[] };

function stepGame(g: Game): Action {
  if (g.cards.length) {
    const card = g.cards[0];
    const index = S1.viewCard(g, card).choices.findIndex(choice => !choice.disabled);
    if (index < 0 || !S1.chooseCard(g, card.uid, index)) throw new Error(`F-CONTENT-CHOICE: ${g.seed}/${card.text}`);
    return { kind: 'choose_card', uid: card.uid, index };
  }
  if (g.phase === 'stop' && g.stop && !g.stop.done) { S1.resolveStop(g, true); return { kind: 'resolve_stop', go: true }; }
  if (g.phase === 'council' && g.council && !g.council.result && S1.currentAgenda(g) && S1.castVote(g)) return { kind: 'cast_vote' };
  if (!S1.primaryAction(g).ok) throw new Error(`F-CONTENT-BLOCKED: ${g.seed}/${g.phase}`);
  S1.advance(g);
  return { kind: 'advance' };
}

function play(seed: string, climate: boolean) {
  const g = S1.createGame(seed);
  S1.enableEventPack(g);
  g.lateOn = true;
  if (climate) S1.enableClimate(g);
  const steps = [];
  let contentChoices = 0;
  for (let step = 0; step < 40 && g.phase !== 'end'; step++) {
    const before = plain(g);
    const action = stepGame(g);
    if (action.kind === 'choose_card' && before.cards.find(card => card.uid === action.uid)?.kind === 'content') contentChoices++;
    steps.push({ seed, step, action, before, after: plain(g) });
  }
  if (steps.length < 30 || !contentChoices) throw new Error(`F-CONTENT-RUN: ${seed}: ${steps.length} steps, ${contentChoices} content choices`);
  return { seed, climate, contentChoices, steps, finalPhase: g.phase, ended: g.phase === 'end' };
}

function fresh(seed: string): Game {
  const g = S1.createGame(seed);
  S1.enableEventPack(g);
  g.cards = [];
  return g;
}

function viewRow(name: string, g: Game, card: Card, choose = true): ViewRow {
  const view = S1.viewCard(g, card);
  const choices: ViewRow['choices'] = [];
  if (choose) view.choices.forEach((choice, index) => {
    if (choice.disabled) return;
    const after = plain(g);
    if (!S1.chooseCard(after, card.uid, index)) throw new Error(`F-CONTENT-ALT: ${name}/${index}`);
    choices.push({ index, after: plain(after) });
  });
  return plain({ name, state: g, card, view, costs: view.choices.map(S1.costLines), pols: view.choices.map(S1.politicsLines), choices });
}

