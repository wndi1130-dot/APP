import { describe, expect, it } from 'vitest';
import { settleJosa } from '../../src/game/josa';

describe('두 갈래 조사 풀이', () => {
  it.each([
    ['꼬리칸과(와)의 약속', '꼬리칸과의 약속'],
    ['경비대과(와)의 약속', '경비대와의 약속'],
    ['기관실을(를) 거쳐 열차(으)로', '기관실을 거쳐 열차로'],
    ['길(으)로, 역(으)로', '길로, 역으로'],
    ['앞칸이(가) 둘, 의무진은(는)', '앞칸이 둘, 의무진은'],
    ['3(으)로 1(으)로 2과(와)', '3으로 1로 2와'],
    ['A과(와)', 'A과(와)'],
  ])('S2와 같은 결과를 낸다: %s', (text, expected) => {
    expect(settleJosa(text)).toBe(expected);
  });

  it('성 첫 글자 뒤 점은 앞의 한글 음절로 판단한다', () => {
    expect(settleJosa('호.이(가)')).toBe('호.가');
  });

  it.each([
    ['블라스타(기관실)이(가) 안건을 냈다', '블라스타(기관실)가 안건을 냈다'],
    ['중환자 분류(기준)을(를) 올릴 때', '중환자 분류(기준)를 올릴 때'],
    ['중환자 분류(기준)(으)로 고쳤다', '중환자 분류(기준)로 고쳤다'],
    ['아동 노동(짐 꾸리기만)(으)로 고쳤다', '아동 노동(짐 꾸리기만)으로 고쳤다'],
    ['복사기(1)을(를)', '복사기(1)를'],
    ['즈덴카(66)이(가) 굶어 죽었다', '즈덴카(66)가 굶어 죽었다'],
    ['기관실(앞칸(둘))은(는)', '기관실(앞칸(둘))은'],
    ['요나 호.(기관실)이(가)', '요나 호.(기관실)가'],
    ['알리(34)(기관실)이(가) 냈다', '알리(34)(기관실)가 냈다'],
    ['얀(34)(기관실)을(를)', '얀(34)(기관실)을'],
  ])('괄호 뒤는 괄호 앞말에 맞춘다: %s', (text, expected) => {
    expect(settleJosa(text)).toBe(expected);
  });

  it('짝 없는 닫는 괄호 뒤는 그대로 둔다', () => {
    expect(settleJosa('기관실)이(가)')).toBe('기관실)이(가)');
    expect(settleJosa('기관실)(둘)이(가)')).toBe('기관실)(둘)이(가)');
  });

  it('두 갈래 표기가 없는 글은 그대로 둔다', () => {
    expect(settleJosa('열차가 역으로 들어왔다.')).toBe('열차가 역으로 들어왔다.');
  });

  it('맨 앞의 두 갈래 표기는 그대로 둔다', () => {
    expect(settleJosa('이(가) 둘')).toBe('이(가) 둘');
  });
});
